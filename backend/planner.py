"""
Action planner + task state machine.

The plan is DETERMINISTIC: built from verified bill fields, not generated by the LLM.
The LLM decides *what the user wants* and *what the bill says*; this file decides *how*,
using only the allowed actions.

Plan step contract:
    {"id": 3, "action": "TYPE", "target": "consumer_id", "value": "DEMO123",
     "say": "Typing your consumer number…", "learn": "Type your consumer number…"}
"""
from i18n import rupees, t

SANDBOX_URL = "/sandbox/index.html"

# Main line shown to judges, in order
STATES = ["CREATED", "READ", "PLANNED", "RUNNING", "WAITING_CONFIRMATION",
          "EXECUTED", "VERIFIED", "COMPLETED"]
# Side states: WAITING_GUARDIAN (family approval), WAITING_USER (OTP handoff), STOPPED
TRANSITIONS = {
    "CREATED": {"READ", "STOPPED"},
    "READ": {"PLANNED", "COMPLETED", "STOPPED"},          # READ_BILL ends at COMPLETED
    "PLANNED": {"RUNNING", "STOPPED"},
    "RUNNING": {"WAITING_CONFIRMATION", "WAITING_USER", "EXECUTED", "STOPPED"},
    "WAITING_CONFIRMATION": {"RUNNING", "WAITING_GUARDIAN", "STOPPED"},
    "WAITING_GUARDIAN": {"RUNNING", "STOPPED"},
    "WAITING_USER": {"RUNNING", "STOPPED"},
    "EXECUTED": {"VERIFIED", "STOPPED"},
    "VERIFIED": {"COMPLETED"},
    "COMPLETED": set(),
    "STOPPED": set(),
}


def build_pay_plan(bill, scenario="normal", lang="en"):
    p = {"provider": bill.get("provider") or "", "cid": bill["consumer_id"], "amount": rupees(bill["amount"])}
    steps = [
        ("OPEN_PAGE", f"{SANDBOX_URL}?scenario={scenario}", None),
        ("READ", "page", None),
        ("TYPE", "consumer_id", bill["consumer_id"]),
        ("CLICK", "fetch_bill", None),
        ("READ", "amount_due", None),
        ("CONFIRM", "payment", None),
        ("CLICK", "pay", None),
        ("READ", "result", None),
    ]
    plan = []
    for i, (action, target, value) in enumerate(steps, 1):
        step = {"id": i, "action": action, "target": target,
                "say": t(f"S{i}", lang, **p), "learn": t(f"L{i}", lang, **p)}
        if value is not None:
            step["value"] = value
        plan.append(step)
    return plan
